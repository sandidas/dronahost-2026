/**
 * Prints the page map with each page's status, Ready or Blocked, and why. Pages with a spec in content/pages are judged by their
 * blueprint (a required section hidden means Blocked, and the missing facts are named). Other pages are judged by the gates in
 * docs/content-planner/project/page-gates.json: unmet refs and owner facts that are still missing.
 * Usage: npx tsx scripts/page-map.ts [--write]   (--write replaces the status table at the end of project/page-map.md)
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { BlueprintsSchema, VisibilitySchema } from "../docs/content-planner/schemas/blueprints";
import { pageStatus } from "../docs/content-planner/tools/content/rules-blueprint";
import pricing from "../data/pricing.json";
import { defaultContext } from "../lib/content/refs";
import { PUBLISHED_PAGES } from "../lib/content/published-pages";

type Gates = { pages: Record<string, { blueprint: string; refs: string[]; facts: string[] }> };
const root = "docs/content-planner/project";
const blueprints = BlueprintsSchema.parse(JSON.parse(readFileSync(`${root}/blueprints.json`, "utf8")));
const gates = JSON.parse(readFileSync(`${root}/page-gates.json`, "utf8")) as Gates;
const visibility = VisibilitySchema.parse(JSON.parse(execFileSync("npx", ["tsx", "scripts/page-visibility.ts"], { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 }).slice(0)));
const ctx = defaultContext;
const families = new Set((pricing.plans as { family?: string }[]).map((p) => p.family));

const unmet = (ref: string): boolean => {
  if (ref.startsWith("claim:")) return !ctx.claimRenders(ref.slice(6));
  if (ref.startsWith("FEATURES.")) return !ctx.flag(ref.slice(9));
  if (ref.startsWith("plans:")) return !families.has(ref.slice(6));
  if (ref.startsWith("pages:")) return PUBLISHED_PAGES.size < Number(ref.slice(6));
  return !ctx.predicate(ref);
};

type Row = { url: string; blueprint: string; spec: boolean; status: "Ready" | "Blocked"; why: string[] };
const rows: Row[] = [];
for (const [path, page] of Object.entries(visibility.pages)) {
  const spec = JSON.parse(readFileSync(`content/pages/${path === "/" ? "home" : path.slice(1)}.json`, "utf8")) as { blueprint?: string };
  const bp = blueprints.blueprints[spec.blueprint ?? ""];
  if (!bp) { rows.push({ url: path, blueprint: spec.blueprint ?? "none", spec: true, status: "Blocked", why: ["the page names no known blueprint"] }); continue; }
  const st = pageStatus(bp, blueprints.heroTypes, page.sections);
  const hiddenParts = [...new Set(page.sections.filter((s) => s.visible).flatMap((s) => s.missing))];
  rows.push({ url: path, blueprint: spec.blueprint ?? "", spec: true, status: st.status, why: st.status === "Ready" ? [`every required section is visible (${page.sections.filter((s) => s.visible).length} of ${page.sections.length} sections); hidden parts need ${hiddenParts.length ? hiddenParts.join(", ") : "nothing"}`] : st.why });
}
for (const [url, g] of Object.entries(gates.pages)) {
  const missingRefs = g.refs.filter(unmet);
  const why = [...missingRefs.map((r) => `needs ${r}`), ...g.facts.map((f) => `owner fact: ${f}`)];
  rows.push({ url, blueprint: g.blueprint, spec: false, status: why.length ? "Blocked" : "Ready", why: why.length ? why : ["its gates are met"] });
}

const md = ["| URL | Blueprint | Page spec | Status | Why |", "|---|---|---|---|---|", ...rows.map((r) => `| \`${r.url}\` | ${r.blueprint} | ${r.spec ? "yes" : "not yet"} | **${r.status}** | ${r.why.join("; ")} |`)].join("\n");
console.log(md);

if (process.argv.includes("--write")) {
  const file = `${root}/page-map.md`;
  const text = readFileSync(file, "utf8");
  const start = "<!-- page-status:start -->";
  const end = "<!-- page-status:end -->";
  const block = `${start}\n\nGenerated by \`npm run content:page-map -- --write\`. A page with a spec is judged by its blueprint; a page without one by the gates in \`page-gates.json\`.\n\n${md}\n\n${end}`;
  const next = text.includes(start) ? text.replace(new RegExp(`${start}[\\s\\S]*${end}`), block) : `${text.trimEnd()}\n\n## Status of each page\n\n${block}\n`;
  writeFileSync(file, next);
}
